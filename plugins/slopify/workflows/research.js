function sameSource(st, a, b) {
  const x = normSource(canon(st, a));
  const y = normSource(canon(st, b));
  if (!x || !y) return false;
  if (x === y) return true;
  const [long, short] = x.length >= y.length ? [x, y] : [y, x];
  return FILE_PATH.test(long) && long.endsWith("/" + short);
}
