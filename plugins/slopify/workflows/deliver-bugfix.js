      skipped.length > 0 ? `Skipped from checkpoints: ${skipped.join(", ")}.` : "",
      `PR: ${state.pr}.`,
      `Review: ${outcome(review2)}.`,
      limits.length > 0 ? `Limits: ${limits.join(" | ")}.` : ""
