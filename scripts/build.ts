// Builds each src/<plugin>/workflows/<name>.ts into plugins/<plugin>/workflows/<name>.js.
//
// The Workflow runtime runs a script's body as an async function and reads its `export const meta`, which must be a
// pure literal and come first. So a source exports `meta` and a default `run()`; the build writes `meta` as JSON,
// bundles `run` with everything it imports, and returns its result from the script body.
//
// Usage: node scripts/build.ts [--check] [name...]. With --check, it writes nothing and fails when an output is stale;
// with names, it builds only those workflows.

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

import { build } from "esbuild";

import { root, workflowFiles, type WorkflowFile } from "./workflows.ts";

const RETURN = "__workflowReturn__";
const RUN_CALL = new RegExp(String.raw`${RETURN}\((await \w+\(\))\);`);

async function bundle(file: WorkflowFile): Promise<string> {
  const rel = path.relative(root, file.source);
  const loaded = (await import(pathToFileURL(file.source).href)) as { meta?: { name?: unknown } };
  const meta = loaded.meta;
  if (meta?.name !== file.name) throw new Error(`${rel}: meta.name must be "${file.name}"`);

  const result = await build({
    stdin: {
      contents: `import run from ${JSON.stringify(`./${file.name}.ts`)};\n${RETURN}(await run());\n`,
      resolveDir: path.dirname(file.source),
      sourcefile: `${file.name}.entry.ts`,
      loader: "ts",
    },
    bundle: true,
    format: "esm",
    platform: "neutral",
    target: "es2022",
    write: false,
    legalComments: "none",
    logLevel: "silent",
  });
  const text = result.outputFiles[0]?.text;
  if (text === undefined) throw new Error(`${rel}: esbuild produced no output`);
  if (!RUN_CALL.test(text)) throw new Error(`${rel}: could not find the run() call in the bundle`);
  const body = text.replace(RUN_CALL, "return $1;");
  if (/^(?:var|let|const|function) meta\b/m.test(body)) {
    throw new Error(`${rel}: the bundle declares its own meta; read workflow metadata through an import instead`);
  }
  return [
    `export const meta = ${JSON.stringify(meta, null, 2)};`,
    `// Generated by scripts/build.ts from ${rel.split(path.sep).join("/")}. Edit the source, not this file.`,
    body,
  ].join("\n");
}

async function readOrEmpty(file: string): Promise<string> {
  try {
    return await readFile(file, "utf8");
  } catch {
    return "";
  }
}

const check = process.argv.includes("--check");
const only = new Set(process.argv.slice(2).filter((a) => !a.startsWith("--")));
const files = await workflowFiles();
const selected = files.filter((f) => only.size === 0 || only.has(f.name));
const built = await Promise.all(selected.map(async (file) => ({ file, text: await bundle(file) })));

const stale: string[] = [];
for (const { file, text } of built) {
  if ((await readOrEmpty(file.target)) === text) continue;
  if (check) stale.push(path.relative(root, file.target));
  else await writeFile(file.target, text);
}
if (stale.length > 0) {
  console.error(`Stale build output; run make build:\n${stale.join("\n")}`);
  process.exitCode = 1;
}
